// Builds the SQL that loads one academic calendar from data/calendario/<calendar>.json
// (made by tools/calendar/extract.py from the FIUBA PDF).
//
//   node tools/calendar/build.mjs 2026-2027
//
// It prints the inserts; paste them in a new migration (see data/calendario/README.md).
// It first deletes the events of that same calendar, so a corrected copy can be loaded
// again in a later migration.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const calendar = process.argv[2];
if (!/^\d{4}-\d{4}$/.test(calendar ?? "")) {
  console.error("Usage: node tools/calendar/build.mjs <calendar, e.g. 2026-2027>");
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const events = JSON.parse(readFileSync(join(root, "data", "calendario", `${calendar}.json`), "utf8"));
const sql = (v) => `'${String(v).replaceAll("'", "''")}'`;
const iso = /^\d{4}-\d{2}-\d{2}$/;

const errors = [];
for (const e of events) {
  if (!e.title || !iso.test(e.starts_on) || !iso.test(e.ends_on) || !Number.isInteger(e.sort)) {
    errors.push(`bad event ${JSON.stringify(e)}`);
  } else if (e.ends_on < e.starts_on) {
    errors.push(`${e.title}: ends before it starts`);
  } else if (new Date(`${e.starts_on}T12:00:00Z`).getUTCDay() !== 1) {
    errors.push(`${e.title}: ${e.starts_on} is not a Monday`);
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const rows = events.map(
  (e) => `  (${sql(calendar)}, ${sql(e.title)}, ${sql(e.starts_on)}, ${sql(e.ends_on)}, ${e.sort})`,
);
process.stdout.write(
  `-- Academic calendar ${calendar}. Generated by tools/calendar/build.mjs from data/calendario/${calendar}.json. Do not edit by hand.\n` +
    `delete from public.academic_events where calendar = ${sql(calendar)};\n` +
    `insert into public.academic_events (calendar, title, starts_on, ends_on, sort) values\n${rows.join(",\n")};\n`,
);
