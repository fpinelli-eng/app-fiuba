// Writes preview.html: the reminder mail of Code.gs (buildMail_()) with sample data, to open
// in a browser. Run after changing the mail:
//
//   node tools/reminders/apps-script/preview.mjs
//
// src/lib/reminders/apps-script.test.ts checks that preview.html is up to date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));

/** Loads Code.gs as Apps Script would (plain script, globals), without Google services. */
export function loadCodeGs() {
  const context = vm.createContext({});
  vm.runInContext(readFileSync(join(here, "Code.gs"), "utf8"), context, { filename: "Code.gs" });
  return context;
}

const escapeAttr = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const escapeText = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function previewHtml(gs = loadCodeGs()) {
  const mails = [gs.buildMail_(gs.sampleRow_())];
  const sections = mails
    .map(
      (m) =>
        `<section><p class="subject"><b>Asunto:</b> ${escapeText(m.subject)}</p>` +
        `<iframe title="${escapeAttr(m.subject)}" srcdoc="${escapeAttr(m.html)}"></iframe>` +
        `<details><summary>Versión de texto</summary><pre>${escapeText(m.text)}</pre></details></section>`,
    )
    .join("\n");
  return `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Mail de Recordarme</title>
<!-- Generated by tools/reminders/apps-script/preview.mjs from Code.gs. Do not edit by hand. -->
<style>
body{margin:0;padding:24px 16px;background:#e9ecf2;font-family:system-ui,sans-serif;color:#1f2537}
h1{font-size:18px;margin:0 auto 16px;max-width:1200px}
main{display:flex;flex-wrap:wrap;gap:24px;justify-content:center;max-width:1200px;margin:0 auto}
section{flex:1 1 320px;min-width:0;max-width:600px}
.subject{font-size:14px;margin:0 0 8px}
iframe{width:100%;height:760px;border:1px solid #cfd4de;border-radius:8px;background:#fff}
pre{white-space:pre-wrap;font-size:13px;background:#fff;padding:12px;border-radius:8px}
</style>
</head>
<body>
<h1>Mail de "Recordarme" (datos de ejemplo)</h1>
<main>
${sections}
</main>
</body>
</html>
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(here, "preview.html"), previewHtml());
  console.log("preview.html actualizado.");
}
