// Builds the SQL that loads the elective areas from data/planes/areas.json.
//
//   node tools/plans-seed/areas.mjs > supabase/migrations/<timestamp>_elective_areas_data.sql
//
// Like the plans seed: once applied, changes go in a new migration.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const areas = JSON.parse(readFileSync(join(root, "data", "planes", "areas.json"), "utf8"));
const meta = JSON.parse(readFileSync(join(root, "data", "planes", "planes.json"), "utf8"));
const sql = (v) => `'${String(v).replaceAll("'", "''")}'`;

const errors = [];
const out = [
  "-- Elective areas. Generated by tools/plans-seed/areas.mjs from data/planes/areas.json. Do not edit by hand.\n",
];

for (const [planId, groups] of Object.entries(areas)) {
  if (planId.startsWith("_")) continue;
  const plan = meta.plans.find((p) => p.id === planId);
  if (!plan) {
    errors.push(`unknown plan ${planId}`);
    continue;
  }
  const subjects = JSON.parse(readFileSync(join(root, "data", "planes", plan.fiuba_map_file), "utf8"));
  const electives = new Set(subjects.filter((s) => s.categoria === "Materias Electivas").map((s) => s.id));
  const seen = new Set();
  const names = Object.keys(groups);
  out.push(
    `insert into public.subject_areas (plan_id, name, sort) values\n${names.map((n, i) => `  (${sql(planId)}, ${sql(n)}, ${i})`).join(",\n")};\n`,
  );
  for (const name of names) {
    for (const code of groups[name]) {
      if (!electives.has(code)) errors.push(`${planId}: ${code} is not an elective`);
      if (seen.has(code)) errors.push(`${planId}: ${code} is in two areas`);
      seen.add(code);
    }
    out.push(
      `update public.subjects set area_id = a.id\nfrom public.subject_areas a\nwhere a.plan_id = ${sql(planId)} and a.name = ${sql(name)}\n  and subjects.plan_id = ${sql(planId)} and subjects.code in (${groups[name].map(sql).join(", ")});\n`,
    );
  }
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
process.stdout.write(out.join("\n"));
