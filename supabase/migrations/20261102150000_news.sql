-- Novedades: the FIUBA academic calendar and announcements ("avisos") from the admins.
--
-- * academic_events: the student activities of the yearly FIUBA academic calendar
--   (PDF), one row per run of weeks (Monday to Saturday). Loaded once a year with a
--   migration made by tools/calendar/ (see data/calendario/README.md). `calendar` is
--   the name of the PDF ('2026-2027'); the app shows the latest one.
-- * news: short announcements published by admins from /admin/novedades.
--
-- Members (FIUBA accounts) read both; only admins write.

create table public.academic_events (
  id bigint generated always as identity primary key,
  calendar text not null,
  title text not null,
  starts_on date not null,
  ends_on date not null check (ends_on >= starts_on),
  sort smallint not null default 0
);

create index academic_events_calendar_idx on public.academic_events (calendar, starts_on);

create table public.news (
  id bigint generated always as identity primary key,
  title text not null check (char_length(title) between 1 and 140),
  body text check (char_length(body) <= 2000),
  url text,
  pinned boolean not null default false,
  published_at timestamptz not null default now()
);

alter table public.academic_events enable row level security;
alter table public.news enable row level security;

grant select, insert, update, delete on public.academic_events to authenticated;
create policy "Members read academic events" on public.academic_events
  for select to authenticated using ((select public.is_member()));
create policy "Admins insert" on public.academic_events
  for insert to authenticated with check ((select public.is_admin()));
create policy "Admins update" on public.academic_events
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins delete" on public.academic_events
  for delete to authenticated using ((select public.is_admin()));

grant select, insert, update, delete on public.news to authenticated;
create policy "Members read news" on public.news
  for select to authenticated using ((select public.is_member()));
create policy "Admins insert" on public.news
  for insert to authenticated with check ((select public.is_admin()));
create policy "Admins update" on public.news
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admins delete" on public.news
  for delete to authenticated using ((select public.is_admin()));

